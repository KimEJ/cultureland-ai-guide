import subprocess, json
d = []
for i, t in enumerate(N, 1):
    subprocess.run(["say", "-v", "Yuna", "-r", "185", "-o", f"s{i}.aiff", t], check=True)
    dur = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f"s{i}.aiff"]).decode())
    d.append(round(dur, 2))
json.dump(d, open("durs.json", "w")); print(d, "total", round(sum(d), 1))
